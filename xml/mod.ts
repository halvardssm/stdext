// xml/mod.ts
//
// JS wrapper for the generated wasm module (xml/_wasm/xml_xml.mjs). Values
// cross the wasm boundary as plain JS objects (serde-wasm-bindgen): options
// and document trees pass through directly, and results come back as
// Standard-Schema-shaped objects — no JSON (de)serialization on the JS side.
//
// Shared types are imported from @std/xml — never redeclared — so this
// package is a true drop-in for @std/xml consumers. The only types declared
// locally (via the wasm module's typescript_custom_section) are XmlIssue,
// XmlParseResult and XmlValidationResult, which @std/xml does not have.
//
// The wrapper's added value over the raw wasm module:
//   1. Re-throwing wasm errors as @std/xml's actual XmlSyntaxError class
//      (the wasm module can only throw plain `Error` — it cannot construct
//      JS classes; @std/xml's XmlSyntaxError has a public constructor taking
//      (message, position), so we use it directly).
//   2. A std-shaped class surface:
//        XML.parse(doc, options?)  → XML (throws XmlSyntaxError when malformed)
//        xml.stringify(opts?)      → string
//        xml.validate(schema)      → { value } | { issues }
//   3. XMLValidator — an XSD schema compiled once into wasm memory,
//      reusable across documents, released on dispose (`using`).
//   4. xml(schema?) → a Standard Schema v1 entity
//      (https://standardschema.dev): issues carry Standard-Schema-shaped
//      `path` segments (element names + sibling indices) derived from the
//      validator's line/column positions, plus std-style `line`/`column`
//      for well-formedness problems, so any Standard Schema consumer can
//      use @stdext/xml schemas.

import {
  parse as wasmParse,
  stringify as wasmStringify,
  XmlSchema as WasmXmlSchema,
} from "./_wasm/xml_xml.mjs";
import type {
  ParseOptions,
  StringifyOptions,
  XmlDeclaration,
  XmlDocument,
  XmlElement,
} from "@std/xml";
import type { StandardSchemaV1 } from "@standard-schema/spec";
import { XmlSyntaxError } from "@std/xml";
import { SchemaError } from "@standard-schema/utils";

// Shared types come straight from @std/xml and are re-exported as-is.
// The document tree produced by the wasm `parse` is structurally identical,
// so these are not casts of convenience — they are the same types.
export type {
  ParseOptions,
  StringifyOptions,
  XmlCDataNode,
  XmlCommentNode,
  XmlDeclaration,
  XmlDocument,
  XmlElement,
  XmlName,
  XmlNode,
  XmlPosition,
  XmlTextNode,
} from "@std/xml";

// Validation types generated by the wasm module. These reference the
// Standard Schema spec types (`@standard-schema/spec`) — the spec's own
// interfaces are NEVER redeclared here.
export type { XmlValidationResult } from "./_wasm/xml_xml.mjs";

// Re-export the spec types so consumers of @stdext/xml don't have to
// depend on @standard-schema/spec to spell the public surface.
export type { StandardSchemaV1 } from "@standard-schema/spec";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/** Position suffix in @std/xml's XmlSyntaxError message style. */
const POSITION_RE = / at line (\d+), column (\d+)$/;

/** Convert a wasm `Error` into @std/xml's XmlSyntaxError. */
function toXmlSyntaxError(error: unknown): XmlSyntaxError {
  if (error instanceof XmlSyntaxError) {
    return error;
  }
  const message = error instanceof Error ? error.message : String(error);
  const match = message.match(POSITION_RE);
  return new XmlSyntaxError(
    match ? message.slice(0, match.index) : message,
    {
      line: Number(match?.[1] ?? 0),
      column: Number(match?.[2] ?? 0),
      offset: 0,
    },
  );
}

/**
 * Attach std-style `line`/`column` to an issue when its message carries a
 * position (wasm parse errors; XSD validation errors do not have one).
 */
function withPosition(issue: StandardSchemaV1.Issue): StandardSchemaV1.Issue {
  const match = issue.message.match(POSITION_RE);
  if (match === null) {
    return issue;
  }
  return {
    ...issue,
    line: Number(match[1]),
    column: Number(match[2]),
  } as StandardSchemaV1.Issue;
}

