/**
 * An XML document tree — `parse` produces it, `stringify` consumes it.
 *
 * Implements @std/xml's `XmlDocument`, so instances can be passed to any
 * consumer of that type.
 */
export class XML implements XmlDocument {
  #document: XmlDocument;

  /** The underlying document tree. */
  get document(): XmlDocument {
    return this.#document;
  }

  get declaration(): XmlDeclaration | undefined {
    return this.document.declaration;
  }

  get root(): XmlElement {
    return this.document.root;
  }

  constructor(document: XmlDocument) {
    this.#document = document;
  }

  /**
   * Parses XML text — or accepts a document tree — into an `XML`, never
   * throwing: every problem is an issue.
   *
   * On success the value is the parsed tree; for a tree input it is that
   * same tree (only its shape is checked — a tree that serializes is
   * representable XML).
   *
   * @param document The XML string or document tree.
   * @param options Options for configuring the parser (@std/xml's
   * `ParseOptions`; `maxAttributes` and `xmlVersion` are accepted and
   * ignored).
   * @returns The Standard Schema result: `{ value }` or `{ issues }`.
   */
  static safeParse(
    document: string | XmlDocument,
    options?: ParseOptions,
  ): StandardSchemaV1.Result<XML> {
    if (typeof document !== "string") {
      try {
        wasmStringify(document, undefined);
        return { value: new XML(document) };
      } catch (error) {
        return { issues: [{ message: toXmlSyntaxError(error).message }] };
      }
    }
    const res = wasmParse(document, options);
    if (res.value === undefined || res.issues !== undefined) {
      return {
        issues: res.issues?.map(withPosition) ?? [{
          message: "cannot parse XML",
        }],
      };
    }
    return { value: new XML(res.value) };
  }

  /**
   * Parses XML text — or accepts a document tree — into an `XML`.
   *
   * @param document The XML string or document tree.
   * @param options Options for configuring the parser.
   * @returns The document.
   * @throws {XmlSyntaxError} If the XML is malformed, has no root element,
   * or is not a valid document tree.
   */
  static parse(document: string | XmlDocument, options?: ParseOptions): XML {
    const res = this.safeParse(document, options);
    if (res.issues !== undefined) {
      throw toXmlSyntaxError(new Error(res.issues[0].message));
    }
    return res.value;
  }

  /**
   * Serializes the document back to an XML string.
   *
   * @param options Serialization options (@std/xml's `StringifyOptions`:
   * `indent` pretty-prints, `declaration` includes the XML declaration).
   * @returns The serialized XML string.
   * @throws {Error} If the tree cannot be serialized (e.g. a comment
   * containing "--").
   */
  stringify(options?: StringifyOptions): string {
    return wasmStringify(this.#document, options);
  }

  /**
   * Validates this document against an XSD schema.
   *
   * @param schema The schema (`XMLValidator` to reuse a compiled schema,
   * or an XML string / document tree to compile it for this call).
   * @returns The Standard Schema result: `{ value }` or `{ issues }`.
   */
  validate(
    schema: XMLValidator | XmlDocument | string,
  ): StandardSchemaV1.Result<XmlDocument> {
    const validator = schema instanceof XMLValidator
      ? schema
      : new XMLValidator(schema);
    return validator.validate(this.#document);
  }
}

/**
 * A compiled XSD schema, reusable for validating many documents.
 *
 * The schema is compiled once, in the constructor. The compiled schema
 * lives in wasm memory: it is released when the validator is garbage
 * collected, or immediately with `using` / `[Symbol.dispose]()`.
 *
 * @example Usage
 * ```ts
 * import { XMLValidator } from "@stdext/xml";
 * import { assert, assertThrows } from "@std/assert";
 *
 * using validator = new XMLValidator(`<xs:schema
 *   xmlns:xs="http://www.w3.org/2001/XMLSchema">
 *   <xs:element name="age" type="xs:positiveInteger"/>
 * </xs:schema>`);
 *
 * assert(validator.validate("<age>25</age>").issues === undefined);
 * assert(validator.validate("<age>-5</age>").issues !== undefined);
 * assertThrows(() => validator.parse("<age>-5</age>"));
 * ```
 */
export class XMLValidator {
  #schema: XmlDocument;
  #validator: WasmXmlSchema;

  /**
   * Compiles the schema.
   *
   * @param schema The XSD schema (XML string or document tree).
   * @throws {XmlSyntaxError} If the schema is not well-formed XML or is an
   * invalid XSD.
   */
  constructor(schema: string | XmlDocument) {
    try {
      this.#schema = XML.parse(schema).document;
      this.#validator = new WasmXmlSchema(schema);
    } catch (error) {
      throw toXmlSyntaxError(error);
    }
  }

  /** The schema document tree. */
  get schema(): XmlDocument {
    return this.#schema;
  }

  /** Releases the compiled schema in wasm memory. */
  [Symbol.dispose](): void {
    this.#validator.free();
  }

  /**
   * Validates a document against the schema. Never throws: every problem
   * is an issue, including well-formedness ones.
   *
   * @param doc The document (XML string, document tree, or `XML`).
   * @returns The Standard Schema result: `{ value }` (the tree — the very
   * same object for a tree input) or `{ issues }`.
   */
  validate(
    doc: string | XmlDocument | XML,
  ): StandardSchemaV1.Result<XmlDocument> {
    const input = doc instanceof XML ? doc.document : doc;
    const result = this.#validator.validate(input);
    if (result.issues !== undefined) {
      return { issues: result.issues.map(withPosition) };
    }
    // A tree input already sits in the caller's hands: hand it back as-is.
    return typeof input === "string" ? { value: result.value } : {
      value: input,
    };
  }

  /**
   * Validates a document against the schema, and returns it as a tree.
   *
   * @param doc The document (XML string, document tree, or `XML`).
   * @returns The document tree.
   * @throws {XmlSyntaxError} If the document is not well-formed XML.
   * @throws {SchemaError} If the document does not conform to the schema.
   */
  parse(doc: string | XmlDocument | XML): XmlDocument {
    const parsed = XML.safeParse(doc instanceof XML ? doc.document : doc);
    if (parsed.issues !== undefined) {
      throw toXmlSyntaxError(new Error(parsed.issues[0].message));
    }
    const result = this.validate(doc);
    if (result.issues !== undefined) {
      throw new SchemaError(result.issues);
    }
    return result.value;
  }
}

// ---------------------------------------------------------------------------
// Standard Schema facade
// ---------------------------------------------------------------------------

/**
 * Create a Standard Schema v1 entity (https://standardschema.dev) for XML,
 * so it can be consumed by any Standard Schema-aware tool.
 *
 * The returned object's `~standard.validate(value)` accepts an XML string
 * or an XmlDocument and never throws for bad input — every problem is an
 * issue:
 *   - not a string or XmlDocument → issue
 *   - not well-formed XML → issue (with `line`/`column` when known)
 *   - with a schema: not conforming → the validator's issues, carrying
 *     best-effort `path`s (element names + sibling indices)
 *
 * On success it returns `{ value: XmlDocument }` (for a tree input, that
 * same tree). The schema is compiled once, when `xml()` is called; an
 * invalid schema throws there.
 *
 * @example Usage
 * ```ts
 * import { xml } from "@stdext/xml";
 * import { assert } from "@std/assert";
 *
 * const schema = xml(`<xs:schema
 *   xmlns:xs="http://www.w3.org/2001/XMLSchema">
 *   <xs:element name="age" type="xs:positiveInteger"/>
 * </xs:schema>`);
 *
 * const result = schema["~standard"].validate("<age>25</age>");
 * assert(!("issues" in result)); // success: result.value is the tree
 *
 * // Without a schema, only well-formedness is checked.
 * assert("issues" in xml()["~standard"].validate("<age>"));
 * ```
 *
 * @param schema The XSD schema (XML string or document tree). When omitted,
 * values are only checked for well-formedness.
 * @returns A Standard Schema v1 entity.
 * @throws {XmlSyntaxError} If the schema is not well-formed XML or is an
 * invalid XSD.
 */
export function xml(
  schema?: string | XmlDocument,
): StandardSchemaV1<string | XmlDocument, XmlDocument> {
  const validator = schema === undefined ? undefined : new XMLValidator(schema);

  return {
    "~standard": {
      version: 1,
      vendor: "@stdext/xml",
      validate: (value: unknown): StandardSchemaV1.Result<XmlDocument> => {
        try {
          if (validator) {
            return validator.validate(value as string | XmlDocument);
          }
          if (typeof value !== "string") {
            // A tree the caller already holds: shape-check it, hand it back.
            wasmStringify(value, undefined);
            return { value: value as XmlDocument };
          }
          const result = wasmParse(value, undefined);
          if (result.issues !== undefined || result.value === undefined) {
            return {
              issues: result.issues?.map(withPosition) ?? [{
                message: "cannot parse XML",
              }],
            };
          }
          return { value: result.value };
        } catch (error) {
          return {
            issues: [{ message: toXmlSyntaxError(error).message }],
          };
        }
      },
    },
  };
}
